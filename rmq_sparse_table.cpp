#include <iostream>
#include <cmath>
using namespace std;
/* Static RMQ */
/* Поиск минимума на отрезке за O(1) с помощью Sparse Table(построение за O(NlogN)) */
/* i-тая строка таблицы отвечает за индекс начала отрезка, j-тый столбец за длину отрезка 2^j */
/* То есть каждый элемент таблицы st[i][j] будет равен минимуму на отрезке начинающегося с индекса i и длиной в 2^j */
int st[100][7]; /* Если размер массива N, то нам нужно только первые log2(N) столбцов(округленный вниз), иначе 2^j превысит размер массива */
int lg[101];
int query(int l, int r){
    int length = r-l+1; /* Длина отрезка */
    int k=lg[length]; /* k это целая степень двойки которая дает длину отрезка(с округлением вниз). Ответ на запросы происходит за O(1) благодаря предподсчету массива lg */
    return min(st[l][k], st[r-(1<<k)+1][k]); /* Для нахождения минимума на отрезке от l до r, мы сравниваем минимум на отрезке начинающегося с l и имеющий длину 2^k, с минимумом отрезка также имеющий длину 2^k, но начинающегося с такой позиции j, что между j и r ровно 2^k элементов. Другими словами j+1+2^k даст индекс конца отрезка r.  */
}

int main(){
    int n;
    cin>>n;
    int a[n];
    for(int i=0;i<n;i++){
        cin>>a[i];
    }

    lg[0]=0; lg[1]=0;
    for (int i = 2; i <= n; i++) {
        lg[i] = lg[i / 2] + 1; /* Считаем log2 с округлением вниз для каждого числа до N. То есть, этот массив будет хранить степени двойки(округленные вниз) которые будут давать длину отрезка равную индексу i для отрезка любой длины(до N). */
    }

    for(int i=0;i<n;i++){
        st[i][0]=a[i]; /* Заполняем базовый слой когда длина отрезка равна 2^0(минимум равен самому числу) */
    }
    int max_log = lg[n]+1;
    for (int j = 1; j < max_log; j++){ /* Заполняем таблицу сверху вниз */
        for (int i = 0; i + (1 << j) <= n; i++){ /* Пока отрезок начинающийся с индекса i и имеющий размер 2^j не выходит за пределы массива */
            st[i][j] = min(st[i][j - 1], st[i + (1 << (j - 1))][j - 1]); /* Для нахождения минимума на отрезке начинающегося с индекса i и длиной 2^j, мы делим этот отрезок на две непересекающиеся половины каждая из которых имеет длину 2^(j-1), что суммарно дает длину исходного отрезка. Вторая половина при этом начинается с индекса i+2^(j-1), то есть с конца первой половины. Сравниваем минимумы этих половин */
        }
    }
    int q,l,r;
    cin>>q;
    for(int i=0;i<q;i++){
        cin>>l>>r;
        cout<<query(l,r)<<"\n";
    }

    return 0;
}