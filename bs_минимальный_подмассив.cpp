#include <iostream>
using namespace std;
// Бинарный поиск по ответу для нахождения минимально возможной длины подмассива сумма элементов которой не меньше K за O(NlogN) для неотрицательного массива. Примечание: способ с двумя указателями лучше, так как работает за O(N)  
int main(){
    int n,k;
    cin>>n>>k;
    int a[n+1], b[n+1];
    for(int i=1;i<=n;i++){
        cin>>a[i];
        if (i==1) b[i]=a[i];
        else b[i]=b[i-1]+a[i];
    }
    int l=1, r=n, ans=-1; // Минимальная длина 1(если один элемент в массиве уже >=k), а максимальная n(если только сумма всех элементов >=k)
    while (l<=r){
        int mid=(l+r)/2; // Выбираем серединную длину подмассива
        bool ok=false;
        for(int i=mid;i<=n;i++){
            int current=b[i]-b[i-mid]; // свойство префикса суммы для нахождения суммы на диапазоне за O(1)
            if (current>=k){ // Если есть подмассив с длиной mid у которого сумма >=K   
                ok=true;
                break;
            }
        }
        if (ok){
            ans=mid; // Условие выполнилось, значит mid потенциально правильный ответ(минимально необходимая длина подмассива)
            r=mid-1; // Значит можно сократить длину подмассива передвинув правую границу
        }
        else{
            l=mid+1; // В ином случае нужно увеличить длину подмассива передвинув левую границу
        }
    }
    cout<<ans;


    return 0;
}