#include <iostream>
using namespace std;
/* Прибавить или вычесть число k ко всем элементам на отрезке за O(1) используя разностный массив (Difference Array) */
int main(){
    int n,k,l,r;
    cin>>n;
    int a[n], b[n+1], c[n];
    for(int i=0;i<n;i++){
        cin>>a[i];
        if (i==0){
            b[i]=a[i];
            continue;
        }
        b[i]=a[i]-a[i-1]; /* Создание разностного массива */
    }
    cin>>l>>r;
    cin>>k;
    b[l]+=k; /* Добавление числа k к индексу l разностного массива также прибавит его ко всем элементам исходного начиная с l */
    b[r+1]-=k; /* Вычитание числа k с индекса r+1 отменит прибавление k для всех элементов после r+1 исходного массива */

    c[0]=b[0];
    cout<<c[0]<<" ";
    for(int i=1;i<n;i++){
        c[i]=c[i-1]+b[i]; /* Массив префиксов суммы разностного массива вернет обновленный массив */
        cout<<c[i]<<" ";
    }

    return 0;
}