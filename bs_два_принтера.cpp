#include <iostream>
using namespace std;
// Бинарный поиск по ответу.
// Есть два принтера, первый печатает 1 лист за x секунд, второй за y. Надо напечатать N листов за минимальное колво времени, при этом можно использовать оба принтера одновременно
int main(){
    int x,y,n;
    cin>>x>>y>>n;
    // Задаем границы
    int l=0,r=min(x,y)*n; // Минимальное время 0 секунд(заведомо невозможно), максимальное время это значение которое получится если использовать только самый быстрый принтер   
    while (l+1<r){ // Продолжаем пока границы не окажутся по соседству. Как только это случается - правая граница и будет правильным ответом
        int mid=(l+r)/2; // Проверяем серединное время 
        if (mid/x+mid/y>=n){ // mid/x+mid/y колво листов которые можно напечатать за mid секунд используя оба принтера. 
            r=mid; // Если mid секунд хватает чтобы напечатать n листов то передвигаем правую границу(потенциально может быть ответом, так как правая граница всегда передвигается при выполнении условия) 
        }
        else{
            l=mid; // Если же этой времени не хватает, то передвигаем левую границу, можно заметить что l всегда будет хранить только недостаточное время
        }
    }
    cout<<r; // Выводим правую границу, так как она всегда является потенциально правильным ответом(потому что правая граница двигалась только при выполнении условии)


    return 0;
}