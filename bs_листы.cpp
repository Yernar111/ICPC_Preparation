#include <iostream>
using namespace std;
// Есть N прямоугольных листов одинаковой ширины W и высоты H. Найти минимальную длину квадратной доски на которой можно разместить все листы
int main() {
    int w, h, n;
    cin>>w>>h>>n;

    long long l = 0; // l — минимальная и заведомо невозможная сторона (0, false)
    long long r = max(w, h) * n; // r — максимальная и заведомо достаточная сторона (все n дипломов в один ряд или столбец, true)

    while (l + 1 < r) {
        int mid = (l + r) / 2; // Проверяем серединную длину

        bool ok = (mid / w) * (mid / h) >= n; // Количество листов которые можно разместить на квадрате длины mid равна произведению количества листов размещенных по ширине и высоте округленных вниз(чтобы листы не выходили за пределы доски). 

        if (ok) { // Если значение этого произведения не меньше необходимого количества 
            r = mid; // Значит стороны mid хватило -> уменьшаем хорошую границу (r)
        } else {
            l = mid; // Стороны mid не хватило -> увеличиваем плохую границу (l)
        }
    }

    cout << r << "\n";

    return 0;
}