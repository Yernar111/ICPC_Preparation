#include <iostream>
#include <algorithm>
using namespace std;
// Бинарный поиск по ответу. Максимизация минимального расстояния между K объектами на N точках на прямой
// Нужно расставить K коров в N стойл с координатами a[i], так чтобы минимальное расстояние между коровами было как можно больше. Гарантируется что количество коров не превышает количество стойл и что все стойла имеют различные координаты 
int main(){
    int n,k; cin>>n>>k;
    int a[n];
    for(int i=0;i<n;i++) cin>>a[i];
    sort(a,a+n); /* Работает только с отсортированными координатами */
    /* Для начала зададим границы */
    int l=1,r=a[n-1]-a[0]; /* Минимальное расстояние 1, максимальное возможное это расстояние между двумя крайними стойлами */
    int ans=0; /* Переменная ans хранит минимальное расстояние между соседними коровами, наша задача увеличить ее как можно больше */
    while (l<=r){
        int mid=(l+r)/2; /* Каждый раз берем среднее расстояние */
        int count=1, pos=a[0]; /* count - количество расставленных коров, pos - координата последней расставленной коровы. В начале всегда ставим одну корову в самое начало */
        for(int i=1;i<n;i++){
            if (a[i]-pos>=mid){ /* Если расстояние между предыдущей коровой больше выбранного значения */
                count++; // Значит корову можно поставить(увеличиваем счетчик и меняем координату последней поставленной коровы)
                pos=a[i];
            }
        }
        if (count>=k){ /* Если количество расставленных коров больше или равно K, значит расстояния mid более чем хватает.  */
            ans=mid;
            l=mid+1; /* Отодвигаем границу чтобы увеличить расстояние  */
        }
        else{ /* Если количество расставленных коров меньше необходимого, значит расстояния mid не хватило */
            r=mid-1; /* Уменьшаем расстояние */
        }
    }
    cout<<ans; // Выводим расстояние между двумя ближайшими коровами после оптимальной расстановки


    return 0;
}