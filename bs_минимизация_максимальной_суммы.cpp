#include <iostream>
using namespace std;
// Минимизация максимальной суммы K подмассивов. Разбить массив на K подмассивов так, чтобы максимальная сумма среди всех подмассивов была минимальной
// Другая вариация этой задачи: Перевести грузы не более чем за K дней, чтобы максимальная грузоподъемность среди всех дней была минимальной 
int main(){
    int n,k;
    cin>>n>>k;
    int a[n];
    int max_a=0,sum_a=0;
    for(int i=0;i<n;i++){
        cin>>a[i];
        max_a=max(max_a,a[i]);
        sum_a+=a[i];
    }
    int l=max_a-1; // Сумма если бы мы делили на N подмассивов. В каждом подмассиве по одному элементу, соответственно ответом будет максимальный элемент. Примечание: отняли 1 чтобы сделать эту границу заведомо невозможной
    int r=sum_a; // Сумма если бы мы делили только на 1 подмассив, то есть случай когда подмассив является самим массивом
    while(l+1<r){ // Продолжаем пока границы не окажутся по соседству. Как только это случается - правая граница и будет правильным ответом.
        int mid=(l+r)/2; // Проверяем серединную сумму
        int current_sum=0, count=1; // current_sum сумма элементов текущего подмассива, count количество подмассивов(начинаем с 1)
        for(int i=0;i<n;i++){
            if(current_sum+a[i]<=mid){ // Если сумма элементов текущего(условного) подмассива не превышает mid, то добавляем элемент в условный подмассив и сохраняем сумму всех ее элементов
                current_sum+=a[i];
            }
            else{ // Если сумма превысила mid, начинаем новый подмассив в котором пока что только один текущий элемент и увеличиваем счетчик подмассивов
                current_sum=a[i];
                count++;
            }
        }
        if (count<=k) r=mid; // Массив можно поделить не более чем на K подмассивов сумма каждой из которых не превышает mid. Можно уменьшить необходимую сумму, поэтому отодвигаем правую границу
        else l=mid; // Количество подмассивов превысило K, значит текущей суммы mid слишком мало и поэтому массив слишком часто делится превышая лимит в условии задачи. Увеличиваем сумму отодвигая левую границу
    }
    cout<<r; // В конце цикла левая и правая граница окажутся соседними значениями, выводим именно правую границу так как в конце поиска она окажется минимальным значением для которого условие выполняется, в то время как левая граница двигалась только когда условие не выполнялось и поэтому в конце примет максимальное значение для которого условие не выполняется.
    return 0;
}