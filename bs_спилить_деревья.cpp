#include <iostream>
using namespace std;
// Дана высота N деревьев. Найти максимальную высоту спила H, при которой суммарно будет собрано не менее M метров древесины.
int main() {
    int n,m;
    cin>>n>>m;

    int a[n];
    int max_a = 0;

    for (int i = 0; i < n; ++i) {
        cin >> a[i];
        max_a = max(max_a, a[i]);
    }

    int l = 0; // l - заведомо подходящая высота спила (высота 0 спилит деревья полностью и гарантированно соберет M метров древесины)
    int r = max_a + 1; // r - заведомо невозможная высота спила (при max_h + 1 спил 0 метров)

    while (l + 1 < r) {
        int mid = (l+r)/2; // Проверяем серединную высоту спила

        int wood = 0; // Счетчик метров срубленной древесины
        for (int i = 0; i < n; ++i) {
            if (a[i]>mid){ // Если высота текущего дерева выше серединной
                wood += a[i] - mid; // Добавляем к счетчику разность высоты дерева и высоты спила 
            }
        }
        if (wood >= m){ // Древесины не меньше требуемого количества, значит высоты спила mid достаточно или мало, пробуем увеличить высоту увеличивая левую границу
            l = mid;
        } else {
            r = mid; // Если древесины мало, значит высота спила слишком большая. Уменьшаем ее снижая правую границу
        }
    }

    cout << l; // Левая граница сохраняет максимальное значение высоты спила которого достаточно чтобы набрать необходимое количество древесины

    return 0;
}