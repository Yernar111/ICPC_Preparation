#include <iostream>
using namespace std;
/* RSQ/RMQ, Point Update */
/* Нахождение минимума на отрезке с помощью Segment Tree за O(logN). Построение за O(N) */
/* Бинарное дерево в котором каждый родитель равен минимуму двух дочерних элементов. Так как дерево complete binary, для родителя с индексом i, индексы дочерних элементов равны 2*i и 2*i+1 */
int n,q,l,r;
int a[100],b[200]; // Бинарное дерево представлено в виде массива, размер которого должен быть в 2 раза больше исходного массива

void update(int i, int new_value){ /* Точечное обновление за log(N) */
    i += n; // Переходим к индексу в дереве и обновляем значение
    b[i] = new_value;
    
    while (i > 1){ // Идем вверх к корню и пересчитываем всех предков
        i /= 2;
        b[i] = min(b[2*i], b[2*i+1]);
    }
}

int query(int l, int r) {
    int res = 1e9; // Очень большое число нужно для того чтобы при поиске минимума на отрезке, любое число из массива было меньше него
    
    // Переходим к индексам в дереве отрезков. Так как последние n элементов дерева равны отдельным числам массива, прибавляем к отрезкам n
    l += n;
    r += n;
    
    while (l <= r) {
        if (l % 2 == 1){ // Если левая граница l — правый сын своего родителя, то мы не можем просто перейти на их родителя, так как левый сын выходит за границы отрезка
            res = min(res, b[l]); /* Поэтому учитываем значение границы */
            l++; /* И передвигаем границу направо, после этого новой границей гарантированно станет левый сын своего родителя, правый сын того же родителя также будет лежать внутри отрезка. И можно будет безопасно перейти к их родителю(минимуму между ними) */
        }
        if (r % 2 == 0) { // Если правая граница r — левый сын своего родителя: логика зеркальна с левой границей. Поэтому рассмотрим случай когда правая граница - правый сын.
            res = min(res, b[r]); /* То есть если условие не срабатывает, можно пока что не брать значение на границе. А просто подняться к их родителю, так как левый сын тоже лежит в отрезке */
            r--;
        }
        // Переходим на уровень выше
        l /= 2;
        r /= 2;
    }
    return res;
}

int main() {
    cin>>n;
    for(int i=0;i<n;i++){
        cin>>a[i];
    }
    
    for (int i = 0; i < n; i++){ /* Заполняем конец массива(что эквивалентно последнему слою дерева) отдельными числами в исходном массиве(для запросов когда отрезок имеет длину 1)  */ 
        b[n + i] = a[i];
    }
    
    for (int i = n - 1; i > 0; i--){ // Продолжаем строить дерево снизу вверх и справа налево(с конца массива до начала) 
        b[i] = min(b[2*i], b[2*i+1]); /* Так как каждый родитель равен минимуму двух дочерних элементов, корень дерева будет равен минимуму всего массива  */
    }
    cin>>q;
    while(q--){
        cin>>l>>r;
        cout<<query(l,r);
    }

    return 0;
}
