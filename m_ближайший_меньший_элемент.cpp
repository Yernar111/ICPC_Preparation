#include <iostream>
#include <stack>
using namespace std;
/* Значение ближайшего меньшего элемента слева для каждого элемента массива за O(n) */
int main(){
    int n;
    cin>>n;
    int a[n],b[n];
    stack <int> c;
    for(int i=0;i<n;i++){
        cin>>a[i];
        b[i]=-1; /* Изначально заполняем -1(означает что меньшего элемента слева нет) */
    }

    for(int i=0;i<n;i++){
        while (!c.empty() && c.top()>=a[i]){ /* Пока последний элемент стека больше чем текущий элемент массива */
            c.pop(); /* Удаляем. Другими словами оставляем в стеке только числа которые меньше текущего числа массива */
        }

        if (!c.empty()){ /* Если в стеке остались элементы, то последний из них и есть ближайший наименьший. Если элементов нет, то для этого индекса останется -1 */
            b[i]=c.top();
        }
        c.push(a[i]); /* Добавляем в стек текущее число */
    }
    for(int i=0;i<n;i++){
        cout<<b[i]<<" ";
    }

    cout<<"\n";
    return 0;
}