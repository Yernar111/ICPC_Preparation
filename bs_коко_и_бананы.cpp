#include <iostream>
using namespace std;
// Коко ест бананы. Даны N кучек бананов и ограничение по времени H часов. Коко каждый час выбирает кучку и съедает K бананов пока в кучке ничего не останется, если в кучке осталось меньше K бананов, то Коко доедает остаток и начинает новую кучку в следующем часу
// Найти минимальную скорость K при котором Коко успеет съесть все бананы не более чем за H часов. H>=N, иначе у задача не имела бы решения
int main() {
    int n, h;
    cin>>n>>h;
    int a[n];
    int max_a = 0;

    for (int i = 0; i < n; ++i) {
        cin >> a[i];
        max_a = max(max_a, a[i]);
    }

    long long l = 0; // l — скорость 0 (заведомо невозможное значение, false)
    long long r = max_a; // r — максимальная кучка (заведомо уложится за N <= H часов, true)

    while (l + 1 < r) {
        int mid = (l+r)/2; // Пробуем серединную скорость

        int total_hours = 0;
        for (int i = 0; i < n; ++i) {
            total_hours += (a[i] + mid - 1) / mid; // Общее количество часов чтобы съесть все бананы(количество бананов в кучке деленная на скорость с округлением вверх для каждой кучки)
        }

        if (total_hours <= h) { // Потраченное количество часов не превышает лимита H. Скорости mid хватило, значит пробуем уменьшить скорость отодвигая правую границу
            r = mid;
        } else {
            l = mid; // Скорости mid не хватило увеличиваем ее сдвигая левую границу
        }
    }

    cout << r << "\n";

    return 0;
}

